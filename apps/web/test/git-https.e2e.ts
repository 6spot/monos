import { createHash } from 'node:crypto';
import { readFile, readdir, mkdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { test, expect } from '@playwright/test';
import type { ConfigurationSnapshot } from '../../../packages/protocol/generated/types.ts';

test('plain Git credentials stay private through save, rotation, clear and logout', async ({ page }, info) => {
  await page.goto('/#projects');
  await page.getByLabel('Password', { exact: true }).fill('monos-browser-test-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await page.getByRole('button', { name: 'New project', exact: true }).click();
  await page.getByLabel('Project name', { exact: true }).fill('Plain Git workspace');
  await page.getByRole('button', { name: 'Add Git repository', exact: true }).click();
  await page.getByLabel('Repository 1 remote URL', { exact: true }).fill('https://git.example.test:8443/Team/Library.git');
  await page.getByLabel('Repository 1 target branch', { exact: true }).fill('trunk');
  await expect(page.getByLabel('Repository 1 merge method', { exact: true })).toHaveCount(0);
  await expect(page.getByRole('region', { name: 'HTTPS Git credential' })).toHaveCount(0);
  await page.getByRole('button', { name: 'Save changes', exact: true }).click();
  const region = page.getByRole('region', { name: 'HTTPS Git credential', exact: true });
  await expect(region).toContainText('Public repositories can be read without a credential.');
  const snapshot = () => page.evaluate(async (): Promise<ConfigurationSnapshot> => (await fetch('/v1/owner/configuration')).json());
  const token = 'synthetic-private-git-token-v1';
  await region.getByLabel('Git username', { exact: true }).fill('repository-bot');
  await region.getByLabel('Git access token', { exact: true }).fill(token);
  await expect(region.getByLabel('Git access token')).toHaveAttribute('type', 'password');
  await region.getByRole('button', { name: 'Save Git credential', exact: true }).click();
  await expect(region).toContainText('Credential configured for repository-bot.');
  await expect(region.getByLabel('Git access token')).toHaveValue('');
  const first = (await snapshot()).git_https_credentials[0]!;
  expect(first.username).toBe('repository-bot');
  expect(JSON.stringify(await snapshot())).not.toContain(token);
  const root = resolve('../..'), dir = resolve(root, 'docs/research/evidence/plain-git-ui-v1/credentials');
  await mkdir(dir, { recursive: true });
  const sources = ['apps/web/src/features/projects.tsx', 'apps/web/src/features/git-https-credential.tsx', 'apps/web/test/git-https.e2e.ts'];
  const hashed = async (path: string) => ({ path, sha256: createHash('sha256').update(await readFile(resolve(root, path))).digest('hex') });
  const views = [];
  for (const [label, width, height] of [['desktop', 1440, 1000], ['mobile', 390, 844]] as const) {
    await page.setViewportSize({ width, height }); await region.scrollIntoViewIfNeeded();
    await expect(region.getByRole('button', { name: 'Clear Git credential', exact: true })).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    const bytes = await page.screenshot(), name = `git-credential-${label}.png`;
    await writeFile(resolve(dir, name), bytes); await info.attach(name, { body: bytes, contentType: 'image/png' });
    views.push({ name, width, height, sha256: createHash('sha256').update(bytes).digest('hex') });
  }
  await writeFile(resolve(dir, 'manifest.json'), JSON.stringify({ sources: await Promise.all(sources.map(hashed)), assets: await Promise.all((await readdir(resolve(root, 'apps/web/dist/assets'))).map(name => hashed('apps/web/dist/assets/' + name))), views, route: page.url(), evidence: 'Built SPA and actual authenticated PostgreSQL configuration commands. Synthetic token and repository endpoint; no remote access.' }, null, 2) + '\n');
  await page.setViewportSize({ width: 1440, height: 1000 });
  await region.getByLabel('Git access token').fill('synthetic-private-git-token-v2');
  await region.getByRole('button', { name: 'Replace Git credential', exact: true }).click();
  await expect(region.getByLabel('Git access token')).toHaveValue('');
  const second = (await snapshot()).git_https_credentials[0]!;
  expect(second.generation).not.toBe(first.generation); expect(second.scope_digest).toBe(first.scope_digest);
  await region.getByRole('button', { name: 'Clear Git credential', exact: true }).click();
  await expect(region).toContainText('Public repositories can be read without a credential.');
  expect((await snapshot()).git_https_credentials).toEqual([]);
  await region.getByLabel('Git access token').fill('synthetic-unsaved-private-token');
  expect(await page.evaluate(() => JSON.stringify([Object.entries(sessionStorage), Object.entries(localStorage)]))).not.toContain('synthetic-');
  await page.getByRole('button', { name: 'Sign out', exact: true }).click();
  await expect(page.getByLabel('Git access token')).toHaveCount(0);
  await page.getByLabel('Password', { exact: true }).fill('monos-browser-test-password');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByLabel('Git access token')).toHaveValue('');
});
